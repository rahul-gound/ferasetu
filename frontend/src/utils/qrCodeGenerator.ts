/**
 * Generates a 2D boolean matrix representing the QR code.
 * true = dark module, false = light module.
 */
export function generateQrMatrix(
  text: string,
  level: ErrorCorrectionLevel = 'M'
): boolean[][] {
  const qr = new QRCodeModel(0, QRErrorCorrectLevel[level]);
  qr.addData(text);
  qr.make();

  const count = qr.getModuleCount();
  const matrix: boolean[][] = [];
  for (let r = 0; r < count; r++) {
    const row: boolean[] = [];
    for (let c = 0; c < count; c++) {
      row.push(qr.isDark(r, c));
    }
    matrix.push(row);
  }
  return matrix;
}

/**
 * Builds an SVG path string from a QR matrix (combines all dark modules into 1 path for optimal performance).
 */
export function generateQrSvgPath(matrix: boolean[][], margin = 4): { path: string; size: number } {
  const moduleCount = matrix.length;
  const size = moduleCount + margin * 2;
  const pathParts: string[] = [];

  for (let r = 0; r < moduleCount; r++) {
    for (let c = 0; c < moduleCount; c++) {
      if (matrix[r][c]) {
        const x = c + margin;
        const y = r + margin;
        pathParts.push(`M${x},${y}h1v1h-1z`);
      }
    }
  }

  return { path: pathParts.join(''), size };
}

/**
 * Generates a full standalone SVG string representing the QR code.
 */
export function generateQrSvgString(
  text: string,
  options: {
    level?: ErrorCorrectionLevel;
    margin?: number;
    size?: number;
    fgColor?: string;
    bgColor?: string;
  } = {}
): string {
  const {
    level = 'M',
    margin = 4,
    size = 256,
    fgColor = '#0f172a',
    bgColor = '#ffffff',
  } = options;

  const matrix = generateQrMatrix(text, level);
  const { path, size: viewBoxSize } = generateQrSvgPath(matrix, margin);

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${viewBoxSize} ${viewBoxSize}" width="${size}" height="${size}" shape-rendering="crispEdges">
  <rect width="100%" height="100%" fill="${bgColor}"/>
  <path d="${path}" fill="${fgColor}"/>
</svg>`;
}

/**
 * Standard NPCI UPI URI Specification
 * Encodes UPI payee address, merchant/shop name, optional amount and note.
 */
export function buildUpiUri(options: {
  upiId: string;
  payeeName: string;
  amount?: number;
  note?: string;
}): string {
  const cleanUpiId = options.upiId.trim();
  const cleanName = options.payeeName.trim();
  const params = new URLSearchParams();
  params.set('pa', cleanUpiId);
  params.set('pn', cleanName);
  params.set('cu', 'INR');

  if (options.amount && options.amount > 0) {
    params.set('am', options.amount.toFixed(2));
  }
  if (options.note) {
    params.set('tn', options.note.trim());
  }

  return `upi://pay?${params.toString()}`;
}

/**
 * Validate a standard Indian UPI ID format (e.g. name@bank, phone@paytm, 9876543210@ybl)
 */
export function isValidUpiId(upiId: string): boolean {
  if (!upiId || typeof upiId !== 'string') return false;
  const trimmed = upiId.trim();
  // Standard UPI ID pattern: 3-50 chars, contains exactly one '@', valid handle
  const upiRegex = /^[a-zA-Z0-9.\-_]{2,49}@[a-zA-Z0-9.\-_]{2,30}$/;
  return upiRegex.test(trimmed);
}
